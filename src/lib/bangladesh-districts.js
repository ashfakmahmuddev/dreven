export const deliveryFeesByZone = {
  dhaka_district: 80,
  dhaka_division: 100,
  outside_dhaka_division: 120,
};

export function getDeliveryZoneForDistrict(district) {
  if (!bangladeshDistricts.includes(district)) return null;
  if (district === 'Dhaka') return 'dhaka_district';
  if (dhakaDivisionDistricts.has(district)) return 'dhaka_division';
  return 'outside_dhaka_division';
}
